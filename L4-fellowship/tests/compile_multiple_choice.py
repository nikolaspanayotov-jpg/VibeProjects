"""Validate and compile the immutable original bank plus four additive test packs."""
from pathlib import Path
import hashlib,html,json,re
ROOT=Path(__file__).resolve().parents[1]
REVISION='2026-11-12-tests-1'
def validate(data,curriculum,start=1):
 expected={'revision','kind','sourceSha256','tests'}|({'id'} if start>1 else set())
 assert set(data)==expected and data['kind']=='derived-learning-tests' and data['revision']==REVISION
 assert data['sourceSha256']==hashlib.sha256((ROOT/'solutions.md').read_bytes()).hexdigest()
 by={k['id']:k for k in curriculum['items']};tests=data['tests'];assert len(tests)==10
 for ti,t in enumerate(tests,start):
  assert set(t)=={'id','title','description','questions'} and t['id']==f'T{ti:02}' and t['title'] and t['description']
  assert len(t['questions'])==10
  for qi,q in enumerate(t['questions'],1):
   assert set(q)=={'id','ksb','prompt','options','answer','source'} and q['id']==f'{t["id"]}-Q{qi:02}'
   assert q['ksb'] in by and 30<=len(q['prompt'])<=500 and len(q['answer'])>=80
   opts=q['options'];assert len(opts)==8 and [o['id'] for o in opts]==list('ABCDEFGH')
   assert len({o['text'] for o in opts})==8 and sum(o['correct'] is True for o in opts) in [3,4]
   for o in opts:
    assert set(o)=={'id','text','why','correct'} and type(o['correct']) is bool
    assert 15<=len(o['text'])<=350 and 15<=len(o['why'])<=300,(q['id'],o)
   s=q['source'];assert set(s)=={'anchor','guideSha256','excerpt'}
   guide=by[q['ksb']]['guide'];plain=re.sub(r'\s+',' ',html.unescape(re.sub('<[^>]+>',' ',guide))).strip()
   assert s['anchor']=='ksb-'+q['ksb'].lower() and s['excerpt'] and s['excerpt'] in plain
   assert s['guideSha256']==hashlib.sha256(guide.encode()).hexdigest()
 return tests
if __name__=='__main__':
 source=(ROOT/'multiple-choice-tests.json').read_text();base=json.loads(source)
 curriculum=json.loads((ROOT/'curriculum.js').read_text().split(' = ',1)[1].rstrip(';\n'))
 legacy=json.loads((ROOT/'tests/multiple_choice_legacy_hashes.json').read_text());assert hashlib.sha256(source.encode()).hexdigest()==legacy['baseSha256']
 tests=list(validate(base,curriculum))
 for t in tests:assert hashlib.sha256(json.dumps(t,sort_keys=True,ensure_ascii=False).encode()).hexdigest()==legacy['tests'][t['id']]
 compiled={**base,'dataSha256':hashlib.sha256(source.encode()).hexdigest()}
 (ROOT/'multiple-choice-data.js').write_text('// Generated by tests/compile_multiple_choice.py; immutable question IDs and revision.\nwindow.L4_TEST_DATA='+json.dumps(compiled,ensure_ascii=False,separators=(',',':')).replace('</','<\\/')+';\n')
 for i in range(1,5):
  path=ROOT/f'test-packs/additional-{i}.json';raw=path.read_text();pack=json.loads(raw);assert pack['id']==f'additional-{i}'
  tests+=validate(pack,curriculum,11+(i-1)*10)
  js='// Generated additive test pack; original questions and revision remain immutable.\n(function(){const d=window.L4_TEST_DATA;if(!d)throw Error("Original test bank missing");d.tests.push(...'+json.dumps(pack['tests'],ensure_ascii=False,separators=(',',':')).replace('</','<\\/')+');d.packSha256=d.packSha256||{};d.packSha256['+json.dumps(pack['id'])+']='+json.dumps(hashlib.sha256(raw.encode()).hexdigest())+';})();\n'
  path.with_suffix('.js').write_text(js)
 questions=[q for t in tests for q in t['questions']];assert len(tests)==50 and len(questions)==500
 assert len({q['id'] for q in questions})==len({q['prompt'] for q in questions})==500
 assert len({tuple(sorted((o['text'],o['correct']) for o in q['options'])) for q in questions})==500,'Reordered option sets are not new questions'
 coverage={k['id']:sum(q['ksb']==k['id'] for q in questions) for k in curriculum['items']};assert min(coverage.values())>=12
 print('Compiled50tests,500distinct questions,4000explained options;original100unchanged;all source refs and hashes verified.')
