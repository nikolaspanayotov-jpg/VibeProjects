"""Validate scenario edition two while retaining the immutable original edition."""
from pathlib import Path
from collections import Counter
import hashlib,html,json,re
ROOT=Path(__file__).resolve().parents[1]
REVISION='2026-11-12-tests-2'
LEGACY='2026-11-12-tests-1'
def digest(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def compile():
 lock=json.loads((ROOT/'tests/multiple_choice_edition_one_hashes.json').read_text())
 assert lock['revision']==LEGACY
 for name,sha in lock['files'].items():assert digest(ROOT/name)==sha,('Original edition changed',name)
 old=json.loads((ROOT/'multiple-choice-tests.json').read_text())['tests']
 for i in range(1,5):old+=json.loads((ROOT/f'test-packs/additional-{i}.json').read_text())['tests']
 curriculum=json.loads((ROOT/'curriculum.js').read_text().split(' = ',1)[1].rstrip(';\n'))
 by={k['id']:k for k in curriculum['items']};revised=[];outputs={};all_questions=[]
 for i in range(1,5):
  path=ROOT/f'test-packs/revised-{i}.json';data=json.loads(path.read_text())
  assert set(data)=={'id','revision','kind','sourceSha256','tests'}
  assert data['id']==f'revised-{i}' and data['revision']==REVISION and data['kind']=='derived-learning-tests'
  assert data['sourceSha256']==digest(ROOT/'solutions.md') and len(data['tests'])==10
  for n,t in enumerate(data['tests'],11+(i-1)*10):
   assert set(t)=={'id','title','description','questions'} and t['id']==f'T{n:02d}'
   assert t['title']==old[n-1]['title'] and len(t['questions'])==10
   assert len({q['objective'].casefold() for q in t['questions']})==10
   assert len({o['text'] for q in t['questions'] for o in q['options']})==80,('Repeated option within a test',t['id'])
   for qn,q in enumerate(t['questions'],1):
    assert set(q)=={'id','ksb','objective','prompt','options','answer','source'}
    assert q['id']==f'{t["id"]}-E2-Q{qn:02d}' and q['ksb'] in by
    assert 3<=len(q['objective'])<=100 and 30<=len(q['prompt'])<=650
    assert 80<=len(q['answer'])<=1500 and len(q['options'])==8
    assert [o['id'] for o in q['options']]==list('ABCDEFGH')
    assert sum(o['correct'] is True for o in q['options']) in [3,4]
    for o in q['options']:
     assert set(o)=={'id','text','why','correct'} and type(o['correct']) is bool
     assert 15<=len(o['text'])<=350 and 15<=len(o['why'])<=450,(q['id'],o)
    source=q['source'];assert set(source)=={'anchor','guideSha256','excerpt'}
    guide=by[q['ksb']]['guide'];plain=re.sub(r'\s+',' ',html.unescape(re.sub('<[^>]+>',' ',guide))).strip()
    assert source['anchor']=='ksb-'+q['ksb'].lower() and source['excerpt'] in plain
    assert source['guideSha256']==hashlib.sha256(guide.encode()).hexdigest()
   revised.append(t);all_questions+=t['questions']
  payload=json.dumps(data['tests'],ensure_ascii=False,separators=(',',':')).replace('</','<\\/')
  if i==1:
   setup=f'if(!d||d.revision!=={json.dumps(LEGACY)}||d.tests.length!==50)throw Error("Original test edition incomplete");d.editions={{[d.revision]:d.tests.slice()}};d.tests=d.tests.slice(0,10);d.revision={json.dumps(REVISION)};d.revisedPackSha256={{}};d.editions[d.revision]=d.tests;'
  else:setup=f'if(!d||d.revision!=={json.dumps(REVISION)}||d.tests.length!=={10*i})throw Error("Revised test pack order incomplete");'
  outputs[path.with_suffix('.js')]='// Generated by tests/compile_revised_tests.py; retain both published editions.\n(function(){const d=window.L4_TEST_DATA;'+setup+'d.tests.push(...'+payload+');d.revisedPackSha256['+json.dumps(data['id'])+']='+json.dumps(digest(path))+';})();\n'
 assert len(revised)==40 and len(all_questions)==400
 assert len({q['id'] for q in all_questions})==len({q['prompt'] for q in all_questions})==400
 assert len({tuple(sorted(o['text'] for o in q['options'])) for q in all_questions})==400
 assert not any('Which statements support a defensible' in q['prompt'] for q in all_questions)
 active=old[:10]+revised;coverage=Counter(q['ksb'] for t in active for q in t['questions']);assert min(coverage.values())>=12
 counts=[[sum(o['correct'] for o in q['options']) for q in t['questions']] for t in revised]
 alternation=sum(value==(3 if i%2==0 else 4) for row in counts for i,value in enumerate(row))
 assert 140<=alternation<=260,('Position predicts answer count',alternation)
 for i in range(10):assert 8<=sum(row[i]==4 for row in counts)<=32,('Answer-count position skew',i)
 repeats=Counter(o['text'] for q in all_questions for o in q['options'])
 assert max(repeats.values())<=4,('Excessive cross-test repetition',repeats.most_common(1))
 # Write only after the complete edition and its archive have passed validation.
 for path,js in outputs.items():path.write_text(js)
 report={'revision':REVISION,'activeTests':50,'activeQuestions':500,'revisedQuestions':400,'originalQuestionsPreserved':500,'uniqueNewOptionStatements':len(repeats),'minimumUniqueOptionsPerRevisedTest':80,'maxCrossTestStatementUse':max(repeats.values()),'oldAlternatingCountMatches':alternation,'requiredCountByPosition':[dict(Counter(row[i] for row in counts)) for i in range(10)],'coverage':dict(coverage)}
 print(json.dumps(report,indent=2));return report
if __name__=='__main__':compile()
