"""Authoring-only packaging of pinned sql.js; the website has no build step.

Usage: python3 tests/pack_sql.py /path/to/original/sql-asm.js
The generated scripts hold trusted vendor source as strings. They are joined
inside a disposable SQL worker, never executed in the page's main context.
"""
from pathlib import Path
import hashlib,json,sys
ROOT=Path(__file__).resolve().parents[1]
SOURCE_SHA256='c83beac167ae9c1af075449555b1db68b24b5280d0fc65c1f7ac4d1cd103459d'
CHUNK_SIZE=64000
source=Path(sys.argv[1]).read_bytes()
assert hashlib.sha256(source).hexdigest()==SOURCE_SHA256,'Use the pinned sql.js 1.13.0 asm distribution.'
text=source.decode('ascii');chunks=[text[n:n+CHUNK_SIZE] for n in range(0,len(text),CHUNK_SIZE)]
folder=ROOT/'vendor';folder.mkdir(exist_ok=True)
for n,chunk in enumerate(chunks):
 header='/* sql.js 1.13.0; generated by tests/pack_sql.py. See ../sql-LICENSE.txt. */\n'
 init='globalThis.L4_SQL_PARTS = globalThis.L4_SQL_PARTS || [];\n'
 (folder/f'sql-asm-{n+1:02d}.js').write_text(header+init+f'globalThis.L4_SQL_PARTS[{n}] = '+json.dumps(chunk)+';\n')
manifest={'version':'1.13.0','source_sha256':SOURCE_SHA256,'bytes':len(source),'parts':len(chunks),'chunk_size':CHUNK_SIZE}
(folder/'sql-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps(manifest))
